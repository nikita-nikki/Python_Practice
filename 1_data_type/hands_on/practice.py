#string
name = 'Hamlet'
print(type(name))

#boolean
is_possible = True
print(type(is_possible))

#list
fruits = ['apple', 'banana', 'orange']      
print(type(fruits))

#tuple
coordinates = (10, 20)  
print(type(coordinates))

#dictionary
student = { "name": "Alice", "age": 20, "grade": "A"}
print(type(student))        



