# len() – Length of an object
fruits = ["apple", "banana", "mango"]
print(len(fruits))

# type() – Check data type
x = 10
y = "Hello"

print(type(x))
print(type(y))

# int(), float(), str()
a = "100"

print(int(a))
print(float(a))
print(str(123))  
# Used for type conversion.

# abs() – Absolute value
print(abs(-15))
print(abs(15))


# max() and min()
nums = [10, 20, 5, 30]

print(max(nums))
print(min(nums))


# sum()
nums = [1, 2, 3, 4]

print(sum(nums))